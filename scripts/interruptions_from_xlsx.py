#!/usr/bin/env python3
"""Turn the "Interruptions" sheet of an SBR data workbook into src/data/interruption-stats.js.

Only aggregates are kept: for each alarm code, its category, its wording, and the alarm durations
(in hours) per robot model. Site names, robot serial numbers (RIN) and time stamps are left out on
purpose, so the published page carries no customer or fleet detail.

    pip install openpyxl
    python3 scripts/interruptions_from_xlsx.py path/to/SBR_Data.xlsx

The mapping from alarm to robot part lives in src/data/interruptions.js and is written by hand.
"""
import json
import os
import re
import sys
from collections import OrderedDict, defaultdict

import openpyxl

COLUMNS = ('Category', 'Reason', 'Code', 'Alarm Duration (h)', 'Robot Type')


def main(path, out):
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    ws = wb['Interruptions']
    rows = ws.iter_rows(values_only=True)
    header = list(next(rows))
    col = {name: header.index(name) for name in COLUMNS}

    codes = OrderedDict()
    models = defaultdict(int)
    skipped = 0
    for r in rows:
        code, cat, reason, hours, model = (r[col[c]] for c in ('Code', 'Category', 'Reason', 'Alarm Duration (h)', 'Robot Type'))
        if code is None or not isinstance(hours, (int, float)) or hours < 0 or not model:
            skipped += 1
            continue
        model = str(model).strip().lower()
        reason = re.sub(r'\s+', ' ', str(reason)).strip()
        e = codes.setdefault(int(code), {'category': str(cat).strip(), 'reasons': [], 'hours': defaultdict(list)})
        if reason not in e['reasons']:
            e['reasons'].append(reason)
        if e['category'] != str(cat).strip():
            raise SystemExit(f'code {code} appears under two categories: {e["category"]!r} and {cat!r}')
        e['hours'][model].append(round(float(hours), 2))
        models[model] += 1

    for e in codes.values():
        e['hours'] = {m: sorted(v) for m, v in sorted(e['hours'].items())}
    stats = OrderedDict(sorted(codes.items(), key=lambda kv: kv[0]))
    source = {'file': re.sub(r'^[0-9a-f]{6,}-', '', os.path.basename(path)), 'rows': sum(models.values()), 'skipped': skipped, 'models': dict(sorted(models.items()))}

    with open(out, 'w', encoding='utf-8') as f:
        f.write('// Generated by scripts/interruptions_from_xlsx.py from the "Interruptions" sheet. Do not edit by hand.\n')
        f.write('// Aggregates only: alarm code, category, wording, and alarm durations in hours per robot model.\n')
        f.write('export const SOURCE = ' + json.dumps(source) + ';\n')
        f.write('export const STATS = {\n')
        for code, e in stats.items():
            f.write(f'  {code}: ' + json.dumps({'category': e['category'], 'reasons': e['reasons'], 'hours': e['hours']}, separators=(',', ':')) + ',\n')
        f.write('};\n')
    print(f'{source["rows"]} events, {len(stats)} alarm codes, models {source["models"]}, skipped {skipped} -> {out}')


if __name__ == '__main__':
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    here = os.path.dirname(os.path.abspath(__file__))
    main(sys.argv[1], os.path.join(here, '..', 'src', 'data', 'interruption-stats.js'))
