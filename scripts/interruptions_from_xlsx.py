#!/usr/bin/env python3
"""Turn the interruptions sheet of an .xlsx export into src/data/interruption-stats.js.

Only aggregates are kept: for each alarm code, its category, its wording, and the alarm lengths (in
hours), pooled over the whole fleet. Site names, robot serial numbers, robot models and time stamps
are left out on purpose, so the published page carries no customer or fleet detail.

    pip install openpyxl
    python3 scripts/interruptions_from_xlsx.py path/to/export.xlsx

The mapping from alarm to robot part lives in src/data/interruptions.js and is written by hand.
"""
import json
import os
import re
import sys
from collections import OrderedDict

import openpyxl

COLUMNS = ('Category', 'Reason', 'Code', 'Alarm Duration (h)')


def main(path, out):
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    ws = wb['Interruptions']
    rows = ws.iter_rows(values_only=True)
    header = list(next(rows))
    col = {name: header.index(name) for name in COLUMNS}

    codes = OrderedDict()
    total = skipped = 0
    for r in rows:
        cat, reason, code, hours = (r[col[c]] for c in COLUMNS)
        if code is None or not isinstance(hours, (int, float)) or hours < 0:
            skipped += 1
            continue
        reason = re.sub(r'\s+', ' ', str(reason)).strip()
        e = codes.setdefault(int(code), {'category': str(cat).strip(), 'reasons': [], 'hours': []})
        if reason not in e['reasons']:
            e['reasons'].append(reason)
        if e['category'] != str(cat).strip():
            raise SystemExit(f'code {code} appears under two categories: {e["category"]!r} and {cat!r}')
        e['hours'].append(round(float(hours), 2))
        total += 1

    for e in codes.values():
        e['hours'].sort()
    stats = OrderedDict(sorted(codes.items(), key=lambda kv: kv[0]))

    with open(out, 'w', encoding='utf-8') as f:
        f.write('// Generated by scripts/interruptions_from_xlsx.py. Do not edit by hand.\n')
        f.write('// Aggregates only: alarm code, category, wording, and alarm lengths in hours, pooled over the fleet.\n')
        f.write('export const SOURCE = ' + json.dumps({'rows': total}) + ';\n')
        f.write('export const STATS = {\n')
        for code, e in stats.items():
            f.write(f'  {code}: ' + json.dumps(e, separators=(',', ':')) + ',\n')
        f.write('};\n')
    print(f'{total} events, {len(stats)} alarm codes, skipped {skipped} -> {out}')


if __name__ == '__main__':
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    here = os.path.dirname(os.path.abspath(__file__))
    main(sys.argv[1], os.path.join(here, '..', 'src', 'data', 'interruption-stats.js'))
